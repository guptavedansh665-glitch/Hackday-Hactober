/**
 * KisanVaani AI — Missing Translation Detector (JavaScript / Node.js)
 * 
 * Identifies untranslated pesticide terms and generates structured
 * GitHub 'Good First Issue' markdown files for community contributors.
 */

const fs = require('fs');
const path = require('path');

class TranslationDetector {
  constructor(localesDir, baseLocale = 'en') {
    this.localesDir = localesDir || path.join(__dirname, '../../locales');
    this.baseLocale = baseLocale;
    this.baseFile = path.join(this.localesDir, `${baseLocale}.json`);

    const raw = fs.readFileSync(this.baseFile, 'utf8');
    this.baseData = JSON.parse(raw);
    this.flatBase = {};
    this._flattenDict('', this.baseData, this.flatBase);
  }

  _flattenDict(prefix, nested, flat) {
    for (const [k, v] of Object.entries(nested)) {
      if (k === 'meta') continue;
      const curr = prefix ? `${prefix}.${k}` : k;
      if (typeof v === 'object' && v !== null && !Array.isArray(v)) {
        this._flattenDict(curr, v, flat);
      } else if (typeof v === 'string') {
        flat[curr] = v;
      }
    }
  }

  auditLocale(localeFilePath) {
    const raw = fs.readFileSync(localeFilePath, 'utf8');
    const targetData = JSON.parse(raw);
    const meta = targetData.meta || {};
    const code = meta.language_code || path.basename(localeFilePath, '.json');
    const name = meta.language_name || code.toUpperCase();

    const flatTarget = {};
    this._flattenDict('', targetData, flatTarget);

    const missing = [];
    let translatedCount = 0;

    for (const [key, baseVal] of Object.entries(this.flatBase)) {
      if (flatTarget[key] && flatTarget[key].trim() && flatTarget[key] !== baseVal) {
        translatedCount++;
      } else {
        const cat = key.split('.')[0];
        const isSafety = ['safety', 'dosage', 'ppe', 'emergency'].some(s => key.includes(s));
        missing.push({
          keyPath: key,
          englishSource: baseVal,
          category: cat,
          isSafetyCritical: isSafety
        });
      }
    }

    const total = Object.keys(this.flatBase).length;
    const coverage = total === 0 ? 0 : Math.round((translatedCount / total) * 1000) / 10;

    return {
      localeCode: code,
      languageName: name,
      totalStrings: total,
      translatedStrings: translatedCount,
      coveragePercentage: coverage,
      missingStrings: missing,
      isComplete: missing.length === 0
    };
  }

  auditAllLocales() {
    const files = fs.readdirSync(this.localesDir)
      .filter(f => f.endsWith('.json') && f !== `${this.baseLocale}.json`)
      .sort();

    return files.map(f => this.auditLocale(path.join(this.localesDir, f)));
  }

  generateGitHubIssueMarkdown(report) {
    const md = [];
    md.push(`## 🌐 [Good First Issue] Add missing ${report.languageName} (\`${report.localeCode}\`) translations\n`);
    md.push(`**Language:** ${report.languageName} (\`${report.localeCode}\`)`);
    md.push(`**Current Coverage:** \`${report.coveragePercentage}%\` (${report.translatedStrings}/${report.totalStrings} strings translated)`);
    md.push(`**Target File:** [\`locales/${report.localeCode}.json\`](file:///locales/${report.localeCode}.json)\n`);
    md.push('### 📝 How to Contribute:');
    md.push(`1. Fork this repository and create a branch: \`git checkout -b i18n-${report.localeCode}\``);
    md.push(`2. Open \`locales/${report.localeCode}.json\` in your code or text editor.`);
    md.push('3. Translate the missing agricultural terms below into accurate, locally accepted phrasing.');
    md.push(`4. Run safety check: \`npm run validate:safety -- --target locales/${report.localeCode}.json\``);
    md.push('5. Submit your Pull Request referencing this issue!\n');
    md.push('### 📋 Missing Strings Checklist\n');

    const categories = {};
    for (const item of report.missingStrings) {
      if (!categories[item.category]) categories[item.category] = [];
      categories[item.category].push(item);
    }

    for (const [cat, entries] of Object.entries(categories)) {
      const formattedCat = cat.replace(/_/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
      md.push(`#### Category: \`${formattedCat}\``);
      for (const entry of entries) {
        const badge = entry.isSafetyCritical ? ' ⚠️ **[Safety-Critical]**' : '';
        md.push(`- [ ] \`${entry.keyPath}\`${badge}`);
        md.push(`  - **English Source:** *"${entry.englishSource}"*`);
        md.push(`  - **Your Translation:** *<add translation here>*`);
      }
      md.push('');
    }

    md.push('---\n*Auto-generated by KisanVaani AI Missing-Translation Detector.*');
    return md.join('\n');
  }
}

// CLI Execution
if (require.main === module) {
  const localesDir = path.join(__dirname, '../../locales');
  const detector = new TranslationDetector(localesDir);
  const reports = detector.auditAllLocales();

  const exportIssues = process.argv.includes('--export-issues');

  console.log('\n==========================================================================');
  console.log('          KisanVaani AI — Multilingual Community Coverage Audit            ');
  console.log('==========================================================================');
  console.log('Locale   | Language               | Coverage   | Missing  | Status');
  console.log('--------------------------------------------------------------------------');
  reports.forEach(r => {
    const status = r.isComplete ? '✅ Complete' : `🟡 ${r.missingStrings.length} strings needed`;
    const code = r.localeCode.padEnd(8);
    const name = r.languageName.padEnd(22);
    const cov = `${r.coveragePercentage.toFixed(1)}%`.padStart(8);
    const miss = `${r.missingStrings.length}`.padEnd(8);
    console.log(`${code} | ${name} | ${cov} | ${miss} | ${status}`);
  });
  console.log('==========================================================================\n');

  if (exportIssues) {
    const outDir = path.join(__dirname, '../../.github/generated_issues');
    fs.mkdirSync(outDir, { recursive: true });
    reports.forEach(r => {
      if (!r.isComplete) {
        const filePath = path.join(outDir, `issue_missing_translations_${r.localeCode}.md`);
        fs.writeFileSync(filePath, detector.generateGitHubIssueMarkdown(r), 'utf8');
        console.log(`✓ Exported Good First Issue: ${filePath}`);
      }
    });
    console.log('');
  }
}

module.exports = { TranslationDetector };
